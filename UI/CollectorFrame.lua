--[[ The data collection window.

	What the collector is doing and what it has: a switch to start and stop it,
	"Automatically run" to have it start at every login, the counts so far, the
	last things it wrote down, and the way out for the data -- Submit data, the
	window below that packs it to send -- and Clear. Opened from the guide window (its ● chip, its ≡ menu
	and its empty body), the minimap button, the options' Data Collection page
	and /apg collect.
]]

local WIDTH, HEIGHT = 360, 470
local PAD = 14
local LOG_LINES = 12

local frame, ui
local function Char() return AP.db.char end

--- Asks before throwing away everything collected (Theme:Confirm, not a StaticPopup: see Theme.lua).
function AP:ConfirmClearData()
	AP.Theme:Confirm({ text = L.COLLECTOR_CLEAR_CONFIRM, accept = L.COLLECTOR_CLEAR, cancel = CANCEL or "Cancel",
		onAccept = function() AP.Collector:Clear() end })
end

--[[ The Submit window.

	Two columns. On the left, the share code (Export.ShareCode) in a box to
	select and copy -- or, as text, the plain export, to see what goes out. On
	the right: the name to be credited under, the two places to send it (the
	GitHub form, which a GitHub Action reads by itself, and our Discord), the
	file route for data too big to paste, and who has sent theirs.

	The game cannot write to the clipboard or open a web page for an addon, so
	the player selects and presses Ctrl+C. Opening the window counts as a send
	for "new since your last send", as the Instance Journal does.
]]
local SUBMIT_W, SUBMIT_H = 720, 540
local LEFT_W = 360
local CONTRIBUTORS_SHOWN = 160 -- characters of names before "and N more"

local submitFrame

--- A one-line box whose text can be selected and copied but not changed.
local function CopyBox(parent, text, width)
	local box = CreateFrame("EditBox", nil, parent)
	box:SetSize(width, 22)
	box:SetAutoFocus(false)
	box:SetTextInsets(6, 6, 0, 0)
	box:SetFontObject(ChatFontNormal)
	Theme:SetFont(box, "body", 11)
	Theme:EditBoxArt(box)
	box:SetText(text)
	box:SetCursorPosition(0)
	box:SetScript("OnTextChanged", function(self, userInput)
		if userInput then
			self:SetText(text)
			self:HighlightText()
		end
	end)
	box:SetScript("OnEditFocusGained", function(self) self:HighlightText() end)
	box:SetScript("OnEditFocusLost", function(self) self:HighlightText(0, 0) end)
	box:SetScript("OnEscapePressed", function(self) self:ClearFocus() end)
	box:SetScript("OnEnterPressed", function(self) self:ClearFocus() end)
	return box
end

--- The contributors, as Data/Contributors.lua lists them (generated by Tools/ingest.py).
function AP:GetContributors()
	local names = {}
	for _, name in ipairs(type(AP.CONTRIBUTORS) == "table" and AP.CONTRIBUTORS or {}) do
		-- The list is cleaned when it is made; a stray UI escape is dropped here all the same.
		if type(name) == "string" then
			name = name:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""):gsub("|", "")
			if name ~= "" then names[#names + 1] = name end
		end
	end
	return names
end

--- The contributors in one line: every name, or as many as fit in `budget` letters and "and N more".
function AP:ContributorsText(budget)
	local names = self:GetContributors()
	if #names == 0 then return L.CONTRIBUTORS_NONE end
	if not budget then return table.concat(names, ", ") end
	local shown, length = {}, 0
	for index, name in ipairs(names) do
		if index > 1 and length + #name > budget then
			return table.concat(shown, ", ") .. ", " .. string.format(L.CONTRIBUTORS_MORE, #names - #shown)
		end
		shown[#shown + 1] = name
		length = length + #name + 2
	end
	return table.concat(shown, ", ")
end

local function KB(text) return string.format("%.1f KB", #text / 1024) end

local function Plural(n, word) return n .. " " .. word .. (n == 1 and "" or "s") end

--- Fills the box: the share code, or the plain text when asked or when the client can't make a code.
local function FillSubmit(f)
	local Export = AP.Export
	local envelope = Export.Envelope()
	local code = not f.asText and Export.ShareCode(envelope) or nil
	local text = code or Export.Build(envelope)
	f.text = text
	f.box:SetText(text)
	f.box:SetCursorPosition(0)
	f.scroll:SetVerticalScroll(0)

	local canCode = Export.CanEncode()
	f.codeHead.label:SetText(code and L.SUBMIT_CODE or L.SUBMIT_TEXT)
	f.intro:SetText(canCode and L.SUBMIT_INTRO or L.SUBMIT_INTRO_TEXT)
	f.as:SetShown(canCode)
	f.as:SetText(f.asText and L.SUBMIT_AS_CODE or L.SUBMIT_AS_TEXT)

	local counts = AP.Collector:Counts()
	local status = string.format(L.SUBMIT_SIZE, KB(text), Plural(counts.quests, "quest"), Plural(counts.levels, "level"))
	if f.newQuests and f.sentBefore then status = status .. string.format(L.SUBMIT_NEW, f.newQuests) end
	if #text > Export.ISSUE_LIMIT then status = status .. " " .. L.SUBMIT_TOO_LONG end
	f.status:SetText(status)
end

local function BuildSubmit()
	local f = CreateFrame("Frame", "AegisPathfinderSubmit", UIParent)
	f:SetFrameStrata("DIALOG")
	f:SetSize(SUBMIT_W, SUBMIT_H)
	f:SetPoint("CENTER", UIParent, "CENTER", 0, 40)
	Theme:Panel(f, "panel")
	Theme:Chrome(f, L.SUBMIT_TITLE, nil)
	tinsert(UISpecialFrames, "AegisPathfinderSubmit")

	local m = Theme.metrics
	local body = CreateFrame("Frame", nil, f)
	body:SetPoint("TOPLEFT", f.subhead, "BOTTOMLEFT", PAD, -12)
	body:SetPoint("BOTTOMRIGHT", f, "BOTTOMRIGHT", -PAD - m.right, PAD + m.bottom)
	local RIGHT_W = SUBMIT_W - m.left - m.right - PAD * 3 - LEFT_W

	-- Left: the code.
	local left = CreateFrame("Frame", nil, body)
	left:SetPoint("TOPLEFT", body, "TOPLEFT", 0, 0)
	left:SetPoint("BOTTOMLEFT", body, "BOTTOMLEFT", 0, 0)
	left:SetWidth(LEFT_W)

	local codeHead = Theme:SectionHeader(left, L.SUBMIT_CODE, LEFT_W)
	codeHead:SetPoint("TOPLEFT", left, "TOPLEFT", 0, 0)
	local intro = Theme:FinePrint(left, LEFT_W)
	intro:SetPoint("TOPLEFT", codeHead, "BOTTOMLEFT", 0, -8)

	local status = Theme:FinePrint(left, LEFT_W)
	status:SetPoint("BOTTOMLEFT", left, "BOTTOMLEFT", 0, 34)

	local holder = CreateFrame("Frame", nil, left)
	holder:SetPoint("TOPLEFT", intro, "BOTTOMLEFT", 0, -10)
	holder:SetPoint("RIGHT", left, "RIGHT", 0, 0)
	holder:SetPoint("BOTTOM", status, "TOP", 0, 8)
	Theme:Inset(holder, "panel2")

	local scroll = CreateFrame("ScrollFrame", nil, holder)
	scroll:SetPoint("TOPLEFT", holder, "TOPLEFT", 8, -8)
	scroll:SetPoint("BOTTOMRIGHT", holder, "BOTTOMRIGHT", -8, 8)
	local box = CreateFrame("EditBox", nil, scroll)
	box:SetMultiLine(true)
	box:SetAutoFocus(false)
	box:SetMaxLetters(0)
	box:SetWidth(LEFT_W - 16)
	box:SetFontObject(ChatFontNormal)
	box:SetScript("OnEscapePressed", function() f:Hide() end)
	-- The text is for copying, not editing: typing puts it back.
	box:SetScript("OnTextChanged", function(self, userInput)
		if userInput and f.text then
			self:SetText(f.text)
			self:HighlightText()
		end
	end)
	scroll:SetScrollChild(box)
	scroll:EnableMouseWheel(true)
	scroll:SetScript("OnMouseWheel", function(self, delta)
		local target = self:GetVerticalScroll() - delta * 40
		self:SetVerticalScroll(math.max(0, math.min(self:GetVerticalScrollRange(), target)))
	end)
	holder:EnableMouse(true)
	holder:SetScript("OnMouseDown", function()
		box:SetFocus()
		box:HighlightText()
	end)

	local selectAll = Theme:PanelButton(left, L.SUBMIT_SELECT, 120, 26)
	selectAll:SetPoint("BOTTOMLEFT", left, "BOTTOMLEFT", 0, 0)
	selectAll:SetScript("OnClick", function()
		box:SetFocus()
		box:HighlightText()
	end)
	local as = Theme:PanelButton(left, L.SUBMIT_AS_TEXT, 100, 26)
	as:SetPoint("LEFT", selectAll, "RIGHT", 6, 0)
	as:SetScript("OnClick", function()
		f.asText = not f.asText
		FillSubmit(f)
	end)

	-- Right: credit, where to send it, the file, contributors.
	local right = CreateFrame("Frame", nil, body)
	right:SetPoint("TOPRIGHT", body, "TOPRIGHT", 0, 0)
	right:SetPoint("BOTTOMRIGHT", body, "BOTTOMRIGHT", 0, 0)
	right:SetWidth(RIGHT_W)

	local creditHead = Theme:SectionHeader(right, L.SUBMIT_CREDIT_HEAD, RIGHT_W)
	creditHead:SetPoint("TOPLEFT", right, "TOPLEFT", 0, 0)
	local creditLabel = right:CreateFontString(nil, "OVERLAY")
	Theme:SetFont(creditLabel, "body", 12)
	Theme:TextColor(creditLabel, Theme:IsBlizzard() and "accent" or "text")
	creditLabel:SetText(L.SUBMIT_CREDIT)
	creditLabel:SetPoint("TOPLEFT", creditHead, "BOTTOMLEFT", 0, -14)
	local credit = CreateFrame("EditBox", nil, right)
	credit:SetSize(RIGHT_W - 100, 22)
	credit:SetPoint("LEFT", creditLabel, "LEFT", 96, 0)
	credit:SetAutoFocus(false)
	credit:SetMaxLetters(AP.Export.CREDIT_MAX)
	credit:SetTextInsets(6, 6, 0, 0)
	credit:SetFontObject(ChatFontNormal)
	Theme:SetFont(credit, "body", 12)
	Theme:EditBoxArt(credit)
	local placeholder = credit:CreateFontString(nil, "OVERLAY")
	Theme:SetFont(placeholder, "body", 12)
	Theme:TextColor(placeholder, "textDim")
	placeholder:SetPoint("LEFT", credit, "LEFT", 6, 0)
	local function ShowPlaceholder()
		placeholder:SetText(L.SUBMIT_CREDIT_EMPTY .. ": " .. (AP.Compat.Call(UnitName, "player") or "?"))
		placeholder:SetShown((credit:GetText() or "") == "" and not credit:HasFocus())
	end
	-- The code carries the name: build it again a moment after the typing stops.
	local edits = 0
	credit:SetScript("OnTextChanged", function(self, userInput)
		ShowPlaceholder()
		if not userInput then return end
		AP.Export.SetCreditName(self:GetText())
		edits = edits + 1
		local this = edits
		C_Timer.After(0.6, function()
			if this == edits and f:IsShown() then FillSubmit(f) end
		end)
	end)
	credit:SetScript("OnEditFocusGained", ShowPlaceholder)
	credit:SetScript("OnEditFocusLost", ShowPlaceholder)
	credit:SetScript("OnEnterPressed", function(self) self:ClearFocus() end)
	credit:SetScript("OnEscapePressed", function(self) self:ClearFocus() end)
	local creditNote = Theme:FinePrint(right, RIGHT_W)
	creditNote:SetPoint("TOPLEFT", creditLabel, "BOTTOMLEFT", 0, -12)
	creditNote:SetText(L.SUBMIT_CREDIT_NOTE)

	local whereHead = Theme:SectionHeader(right, L.SUBMIT_WHERE, RIGHT_W)
	whereHead:SetPoint("TOPLEFT", creditNote, "BOTTOMLEFT", 0, -16)
	local githubLabel = Theme:FinePrint(right, RIGHT_W)
	githubLabel:SetPoint("TOPLEFT", whereHead, "BOTTOMLEFT", 0, -8)
	githubLabel:SetText(L.SUBMIT_GITHUB)
	local github = CopyBox(right, AP.Export.GITHUB_URL, RIGHT_W - 4)
	github:SetPoint("TOPLEFT", githubLabel, "BOTTOMLEFT", 2, -4)
	local discordLabel = Theme:FinePrint(right, RIGHT_W)
	discordLabel:SetPoint("TOPLEFT", github, "BOTTOMLEFT", -2, -8)
	discordLabel:SetText(L.SUBMIT_DISCORD)
	local discord = CopyBox(right, AP.Export.DISCORD_URL, RIGHT_W - 4)
	discord:SetPoint("TOPLEFT", discordLabel, "BOTTOMLEFT", 2, -4)
	local linkHint = Theme:FinePrint(right, RIGHT_W)
	linkHint:SetPoint("TOPLEFT", discord, "BOTTOMLEFT", -2, -6)
	linkHint:SetText(L.LINK_HINT)

	local fileHead = Theme:SectionHeader(right, L.SUBMIT_FILE, RIGHT_W)
	fileHead:SetPoint("TOPLEFT", linkHint, "BOTTOMLEFT", 0, -16)
	local fileText = Theme:FinePrint(right, RIGHT_W)
	fileText:SetPoint("TOPLEFT", fileHead, "BOTTOMLEFT", 0, -8)
	fileText:SetText(L.SUBMIT_FILE_TEXT)
	local save = Theme:PanelButton(right, L.SUBMIT_SAVE, 170, 24)
	save:SetPoint("TOPLEFT", fileText, "BOTTOMLEFT", 0, -8)
	save:SetScript("OnClick", function() ReloadUI() end)

	local thanksHead = Theme:SectionHeader(right, L.CONTRIBUTORS, RIGHT_W)
	thanksHead:SetPoint("TOPLEFT", save, "BOTTOMLEFT", 0, -16)
	local thanks = Theme:FinePrint(right, RIGHT_W)
	thanks:SetPoint("TOPLEFT", thanksHead, "BOTTOMLEFT", 0, -8)
	Theme:TextColor(thanks, "text")
	thanks:SetText(AP:ContributorsText(CONTRIBUTORS_SHOWN))
	local thanksFoot = Theme:FinePrint(right, RIGHT_W)
	thanksFoot:SetPoint("TOPLEFT", thanks, "BOTTOMLEFT", 0, -4)
	thanksFoot:SetText(L.CONTRIBUTORS_FOOT)

	f:HookScript("OnShow", function(self)
		if not credit:HasFocus() then credit:SetText(AP.Export.GetCreditName()) end
		ShowPlaceholder()
		-- Counted before this showing marks everything as sent.
		local newQuests, _, sentAt = AP.Export.NewSinceSent()
		self.newQuests, self.sentBefore = newQuests, sentAt ~= nil
		FillSubmit(self)
		AP.Export.MarkSent()
		Theme:FadeIn(self, 0.2)
	end)
	f:HookScript("OnHide", function()
		credit:ClearFocus()
		box:ClearFocus()
	end)

	f.box, f.scroll, f.status, f.intro, f.codeHead, f.as = box, scroll, status, intro, codeHead, as
	f.credit, f.github, f.discord, f.thanks = credit, github, discord, thanks
	f:Hide()
	submitFrame = f
	AP.submitframe = f
end

--- Opens the Submit window with the code selected, ready for Ctrl+C.
function AP:ShowSubmit()
	if not submitFrame then BuildSubmit() end
	if submitFrame:IsShown() then
		FillSubmit(submitFrame)
	else
		submitFrame:Show()
	end
	submitFrame.box:SetFocus()
	submitFrame.box:HighlightText()
end
AP.ShowExport = AP.ShowSubmit

--[[ The window ]]

local function Stat(parent, label, x, y)
	local value = parent:CreateFontString(nil, "OVERLAY")
	Theme:SetFont(value, "display", 20)
	value:SetPoint("TOPLEFT", parent, "TOPLEFT", x, y)
	Theme:TextColor(value, "text")
	local name = parent:CreateFontString(nil, "OVERLAY")
	Theme:SetFont(name, "body", 10)
	name:SetPoint("TOPLEFT", value, "BOTTOMLEFT", 0, -1)
	name:SetText(label:upper())
	Theme:TextColor(name, "textDim")
	return value
end

local function Build()
	frame = CreateFrame("Frame", "AegisPathfinderCollector", UIParent)
	AP.collectorframe = frame
	frame:SetFrameStrata("DIALOG")
	frame:SetSize(WIDTH, HEIGHT)
	frame:SetPoint("TOPRIGHT", AP.objectiveframe, "TOPLEFT", -8, 0)
	Theme:Panel(frame, "panel")
	Theme:Chrome(frame, L.COLLECTOR_TITLE, Theme:PositionSaver("collectorframe"))
	Theme:RestorePosition(frame, "collectorframe")
	tinsert(UISpecialFrames, "AegisPathfinderCollector")
	frame:Hide()
	ui = {}
	frame.ui = ui

	local m = Theme.metrics
	local body = CreateFrame("Frame", nil, frame)
	body:SetPoint("TOPLEFT", frame.subhead, "BOTTOMLEFT", PAD, -12)
	body:SetPoint("BOTTOMRIGHT", frame, "BOTTOMRIGHT", -PAD - m.right, PAD + m.bottom)
	local W = WIDTH - PAD * 2 - m.left - m.right

	-- State: a dot, collecting or not, and the switch.
	local dot = body:CreateTexture(nil, "ARTWORK")
	dot:SetTexture(Theme.texture.circleFill)
	dot:SetSize(10, 10)
	dot:SetPoint("TOPLEFT", body, "TOPLEFT", 0, -6)
	ui.dot = dot

	local state = body:CreateFontString(nil, "OVERLAY")
	Theme:SetFont(state, "display", 16)
	state:SetPoint("LEFT", dot, "RIGHT", 8, 0)
	ui.state = state

	local toggle = Theme:PanelButton(body, L.START_COLLECTING, W, 28)
	toggle:SetPoint("TOPLEFT", body, "TOPLEFT", 0, -26)
	toggle:SetScript("OnClick", function() AP.Collector:Toggle() end)
	ui.toggle = toggle

	local auto = Theme:Checkbox(body, L.COLLECTOR_AUTO, function(on) AP.Collector:SetAuto(on) end)
	auto:SetPoint("TOPLEFT", toggle, "BOTTOMLEFT", 0, -10)
	auto:Fit()
	ui.auto = auto

	local autoNote = Theme:FinePrint(body, W)
	autoNote:SetPoint("TOPLEFT", auto, "BOTTOMLEFT", 0, -2)
	autoNote:SetText(L.COLLECTOR_AUTO_NOTE)

	-- What it has so far.
	local stats = Theme:SectionHeader(body, "Collected", W)
	stats:SetPoint("TOPLEFT", autoNote, "BOTTOMLEFT", 0, -14)
	local grid = CreateFrame("Frame", nil, body)
	grid:SetSize(W, 40)
	grid:SetPoint("TOPLEFT", stats, "BOTTOMLEFT", 0, -8)
	local col = W / 4
	ui.quests = Stat(grid, "Quests", 0, 0)
	ui.turnedIn = Stat(grid, "Turned in", col, 0)
	ui.pickups = Stat(grid, "Picked up", col * 2, 0)
	ui.levels = Stat(grid, "Levels", col * 3, 0)

	-- The last things it wrote down.
	local recent = Theme:SectionHeader(body, "Recent", W)
	recent:SetPoint("TOPLEFT", grid, "BOTTOMLEFT", 0, -10)
	ui.lines = {}
	for i = 1, LOG_LINES do
		local fs = body:CreateFontString(nil, "OVERLAY")
		Theme:SetFont(fs, "body", 11)
		fs:SetWidth(W)
		fs:SetJustifyH("LEFT")
		fs:SetWordWrap(false)
		fs:SetPoint("TOPLEFT", recent, "BOTTOMLEFT", 0, -6 - (i - 1) * 14)
		Theme:TextColor(fs, "textDim")
		ui.lines[i] = fs
	end

	-- Submit and clear.
	local submit = Theme:PanelButton(body, L.COLLECTOR_EXPORT, (W - 8) / 2, 26)
	submit:SetPoint("BOTTOMLEFT", body, "BOTTOMLEFT", 0, 0)
	submit:SetScript("OnClick", function() AP:ShowSubmit() end)
	local clear = Theme:PanelButton(body, L.COLLECTOR_CLEAR, (W - 8) / 2, 26)
	clear:SetPoint("BOTTOMRIGHT", body, "BOTTOMRIGHT", 0, 0)
	clear:SetScript("OnClick", function() AP:ConfirmClearData() end)

	frame:HookScript("OnShow", function(self)
		Char().collectoropen = true
		AP:RefreshCollectorFrame()
		Theme:FadeIn(self, 0.2)
	end)
	frame:HookScript("OnHide", function() Char().collectoropen = false end)
	AP.Collector:OnChange(function() if frame:IsShown() then AP:RefreshCollectorFrame() end end)
end

function AP:RefreshCollectorFrame()
	if not frame then return end
	local Collector = self.Collector
	local running = Collector:IsRunning()
	Theme:Tint(ui.dot, running and "accent" or "subtle")
	ui.state:SetText((running and L.COLLECTOR_ON or L.COLLECTOR_OFF):upper())
	Theme:TextColor(ui.state, running and "accent" or "textDim")
	ui.toggle:SetText(running and L.STOP_COLLECTING or L.START_COLLECTING)
	ui.toggle:SetActive(running)
	ui.auto:SetOn(Collector:IsAuto())

	local counts = Collector:Counts()
	ui.quests:SetText(counts.quests)
	ui.turnedIn:SetText(counts.turnedIn)
	ui.pickups:SetText(counts.pickups)
	ui.levels:SetText(counts.levels)

	local log = Collector:GetLog()
	for i = 1, LOG_LINES do
		local line = log[#log - i + 1]
		ui.lines[i]:SetText(line or (i == 1 and L.COLLECTOR_LOG_EMPTY or ""))
	end
end

function AP:ToggleCollectorFrame()
	if not frame then return end
	frame:SetShown(not frame:IsShown())
end

function AP:ResetCollectorPosition()
	if not frame then return end
	frame:ClearAllPoints()
	frame:SetPoint("TOPRIGHT", AP.objectiveframe, "TOPLEFT", -8, 0)
end

AP:OnInit(Build)
